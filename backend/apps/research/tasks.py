@contextmanager
def execution(job_id, ai=False):
    from filelock import FileLock, Timeout

    if not Job.objects.filter(pk=job_id, state="queued").update(
        state="running", started_at=timezone.now(), error="", progress=1
    ):
        yield None
        return
    job = Job.objects.get(pk=job_id)
    lock = None
    try:
        if ai:
            Path(settings.AI_RESOURCE_LOCK).parent.mkdir(parents=True, exist_ok=True)
            lock = FileLock(settings.AI_RESOURCE_LOCK, timeout=1)
            lock.acquire()
        yield job
        job.refresh_from_db()
        job.state = "succeeded"
        job.progress = 100
        job.finished_at = timezone.now()
        job.save()
    except Exception as exc:
        import logging

        logging.getLogger(__name__).exception("Job failed: %s", job_id)
        Job.objects.filter(pk=job_id).update(
            state="failed",
            error=(
                "Recurso AI ocupado; reintenta cuando termine el trabajo actual."
                if isinstance(exc, Timeout)
                else f"{type(exc).__name__}: {str(exc)[:500]}"
            ),
            finished_at=timezone.now(),
        )
    finally:
        if lock is not None:
            lock.release()


@shared_task
def preprocess(job_id):
    from ai.preprocessing import transform

    with execution(job_id) as job:
        if job is None:
            return
        ids = job.config["images"]
        recipe = {k: v for k, v in job.config.items() if k != "images"}
        for index, image in enumerate(ImageAsset.objects.filter(id__in=ids)):
            if ImageVariant.objects.filter(job=job, image=image).exists():
                continue
            with image.file.open("rb") as f:
                data = f.read()
            if hashlib.sha256(data).hexdigest() != image.sha256:
                raise ValueError("El original no coincide con su hash; no se generó el derivado.")
            output, boxes = transform(data, image.annotations, recipe)
            variant = ImageVariant(
                image=image,
                job=job,
                source_revision=image.revision,
                recipe=recipe,
                annotations=boxes,
                width=recipe["size"],
                height=recipe["size"],
                sha256=hashlib.sha256(output).hexdigest(),
            )
            variant.file.save(f"{variant.pk}.png", ContentFile(output))
            Job.objects.filter(pk=job.pk).update(
                progress=int((index + 1) / len(ids) * 95)
            )
        job.result = {
            "variants": list(
                ImageVariant.objects.filter(job=job).values_list("id", flat=True)
            )
        }
        job.result["variants"] = [str(x) for x in job.result["variants"]]
        job.save(update_fields=["result"])


def unpack(version, folder):
    import yaml

    with zipfile.ZipFile(version.archive.path) as z:
        # Archives are generated by our freeze service, never user-controlled ZIPs here.
        for name in z.namelist():
            if Path(name).is_absolute() or ".." in Path(name).parts:
                raise ValueError("Archivo de versión inválido.")
        z.extractall(folder)
    for item in version.manifest:
        data = (Path(folder) / "images" / item["split"] / item["file"]).read_bytes()
        if hashlib.sha256(data).hexdigest() != item["sha256"]:
            raise ValueError("Hash de snapshot inválido.")
    path = Path(folder) / "data.yaml"
    path.write_text(
        yaml.safe_dump(
            {
                "path": str(folder),
                "train": "images/train",
                "val": "images/val",
                "test": "images/test",
                "names": {0: "rona"},
            }
        )
    )
    return str(path)


@shared_task
def train(job_id):
    with execution(job_id, ai=True) as job:
        if job is None:
            return
        from ultralytics import YOLO
        import torch
        import ultralytics

        run = TrainingRun.objects.get(job=job)
        with tempfile.TemporaryDirectory() as folder:
            data = unpack(run.version, folder)
            model = YOLO(run.architecture)

            def epoch(trainer):
                metrics = {k: float(v) for k, v in trainer.metrics.items()}
                run.epochs_log.append({"epoch": trainer.epoch + 1, "metrics": metrics})
                run.save(update_fields=["epochs_log"])
                Job.objects.filter(pk=job.pk).update(
                    progress=min(
                        95, int((trainer.epoch + 1) / job.config["epochs"] * 95)
                    )
                )

            model.add_callback("on_fit_epoch_end", epoch)
            config = {
                k: v
                for k, v in job.config.items()
                if k not in ["version", "architecture"]
            }
            run.environment = {
                "python": platform.python_version(),
                "torch": torch.__version__,
                "ultralytics": ultralytics.__version__,
                "device": settings.AI_DEVICE,
                "platform": platform.platform(),
                "cuda": torch.version.cuda,
                "dataset_hash": run.version.manifest_hash,
            }
            run.save(update_fields=["environment"])
            results = model.train(
                data=data,
                project=str(Path(folder) / "runs"),
                name="training",
                device=settings.AI_DEVICE,
                workers=0,
                plots=True,
                **config,
            )
            run.metrics = {k: float(v) for k, v in results.results_dict.items()}
            run.save(update_fields=["metrics"])
            weights = Path(model.trainer.best)
            contents = weights.read_bytes()
            trained = AIModel(
                run=run,
                name=f"{run.architecture.removesuffix('.pt')} · {str(run.pk)[:8]}",
                sha256=hashlib.sha256(contents).hexdigest(),
            )
            trained.weights.save(f"{trained.pk}.pt", ContentFile(contents))
            # Persist curves and logs alongside weights, accessible through a protected endpoint.
            artifacts = Path(settings.MEDIA_ROOT) / "training-artifacts" / str(run.pk)
            artifacts.mkdir(parents=True, exist_ok=True)
            for path in Path(model.trainer.save_dir).iterdir():
                if path.is_file() and path.suffix in [".png", ".csv", ".yaml"]:
                    shutil.copy2(path, artifacts / path.name)
            job.result = {"model_id": str(trained.pk), "metrics": run.metrics}
            job.save(update_fields=["result"])


@shared_task
def infer(job_id):
    from ai.engine import predict

    with execution(job_id, ai=True) as job:
        if job is None:
            return
        inspection = Inspection.objects.select_related("model").get(job=job)
        start = perf_counter()
        if (
            hashlib.sha256(Path(inspection.model.weights.path).read_bytes()).hexdigest()
            != inspection.model.sha256
        ):
            raise ValueError("Los pesos cambiaron respecto a su hash.")
        boxes, elapsed, output = predict(
            inspection.model.weights.path,
            inspection.model.sha256,
            inspection.original.path,
            job.config["confidence"],
            settings.AI_DEVICE,
        )
        inspection.detections = boxes
        inspection.inference_ms = elapsed
        inspection.annotated.save(
            f"{inspection.pk}.png", ContentFile(output), save=False
        )
        inspection.total_ms = (perf_counter() - start) * 1000
        inspection.save()
        job.result = {"inspection_id": str(inspection.pk), "count": len(boxes)}
        job.save(update_fields=["result"])


@shared_task
def validate_model(job_id):
    from ai.engine import predict, load_model

    with execution(job_id, ai=True) as job:
        if job is None:
            return
        evaluation = Evaluation.objects.select_related("model", "version").get(job=job)
        model = evaluation.model
        if (
            hashlib.sha256(Path(model.weights.path).read_bytes()).hexdigest()
            != model.sha256
        ):
            raise ValueError("Hash de pesos inválido.")
        with tempfile.TemporaryDirectory() as folder:
            data = unpack(evaluation.version, folder)
            detector = load_model(model.weights.path, model.sha256)
            metrics = detector.val(
                data=data,
                split="test",
                device=settings.AI_DEVICE,
                verbose=False,
                plots=False,
                project=str(Path(folder) / "validation"),
            )
            evaluation.metrics = {
                "detection": {k: float(v) for k, v in metrics.results_dict.items()},
                "unit": "imagen; clasificación agregada por fruto en resumen",
                "hardware": platform.platform(),
                "device": settings.AI_DEVICE,
            }
            evaluation.save(update_fields=["metrics"])
            items = {
                x["image_id"]: x
                for x in evaluation.version.manifest
                if x["split"] == "test"
            }
            samples = list(evaluation.samples.all())
            for i, sample in enumerate(samples):
                path = (
                    Path(folder)
                    / "images/test"
                    / items[sample.image_id_snapshot]["file"]
                )
                start = perf_counter()
                boxes, elapsed, _ = predict(
                    model.weights.path,
                    model.sha256,
                    path,
                    evaluation.confidence,
                    settings.AI_DEVICE,
                )
                sample.system_positive = bool(boxes)
                sample.system_ms = (perf_counter() - start) * 1000
                sample.save()
                Job.objects.filter(pk=job.pk).update(
                    progress=int((i + 1) / len(samples) * 95)
                )
            job.result = evaluation.metrics
            job.save(update_fields=["result"])
